var (
	_ resource.Resource                = &ProtectedResourceResource{}
	_ resource.ResourceWithImportState = &ProtectedResourceResource{}
)

type ProtectedResourceResource struct {
	client *client.Client
}

func NewProtectedResourceResource() resource.Resource {
	return &ProtectedResourceResource{}
}

func (r *ProtectedResourceResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_protected_resource"
}

